import 'dart:convert';
import 'dart:io';

Future<void> main() async {
  final result = await Process.run('flutter', ['gen-l10n']);
  stdout.write(result.stdout);
  stderr.write(result.stderr);
  if (result.exitCode != 0) {
    exitCode = result.exitCode;
    return;
  }
  final arb = jsonDecode(
    await File('lib/l10n/app_en.arb').readAsString(),
  ) as Map<String, dynamic>;
  final cases = <String>[];
  final errors = <String>[];
  for (final key in arb.keys.where((key) => !key.startsWith('@'))) {
    cases.add("    '$key' => messages.$key,");
    final metadata = arb['@$key'] as Map<String, dynamic>?;
    if (metadata?['source'] is String) {
      errors.add('    ${jsonEncode(metadata!['source'])} => messages.$key,');
    }
  }
  await File('lib/generated/l10n/lookup.dart').writeAsString(
    '''// Generated by tool/generate_localizations.dart. Do not edit.
import 'app_localizations.dart';
String localizedMessage(AppLocalizations messages, String key) => switch(key) {
${cases.join('\n')}
  _ => key,
};
String? localizedBackendError(AppLocalizations messages,String source)=>switch(source){
${errors.join('\n')}
  _ => null,
};
''',
  );
}
